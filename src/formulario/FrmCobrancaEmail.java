    public final void carregaGrelha() {

        DefaultTableModel modelo = (DefaultTableModel) tabelaCobranca.getModel();
        modelo.setNumRows(0);
        int ckBusca = 1;
        int id_responsavel = Session.getIdUsuario();

        if (!ckPendente.isSelected() && !ckFinalizado.isSelected()) {
            ckPendente.setSelected(true);
        }

        if (ckPendente.isSelected() && !ckFinalizado.isSelected()) {
            ckBusca = 1;
        }

        if (!ckPendente.isSelected() && ckFinalizado.isSelected()) {
            ckBusca = 2;
        }

        if (ckPendente.isSelected() && ckFinalizado.isSelected()) {
            ckBusca = 3;
        }

        // Validar ver todos
        if (ckVerTodos.isSelected()) {
            id_responsavel = 0;
        }

        List<Cobranca> lista = cobrancaoDao.getListagemCobrancasAlls(ckBusca, txtPesquisa.getText(), id_responsavel);

        for (Cobranca cobranca : lista) {

            modelo.addRow(new Object[]{
                cobranca.getIdCobranca(),
                cobranca.getData(),
                cobranca.getProtocolo(),
                cobranca.getFuncionario().getNome(),
                cobranca.getFuncionario().getEmail(),
                cobranca.getFuncionario().getLocalidade().getNomeLocalidade(),
                cobranca.getMotivo(),
                cobranca.getStatus(),
                cobranca.getQuantidade(),
                cobranca.getDataEnvio(),
                cobranca.getUsuarioEnvio().getNome(),
                false,});
        }

        txtQuantidade.setText("Quantidade: " + lista.size());

        pinta();
    }

