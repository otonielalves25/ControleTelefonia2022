    private void btnPesquisaRapidaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisaRapidaActionPerformed
        // TODO add your handling code here:

        FrmEmprestimoConsultaRapida frm = new FrmEmprestimoConsultaRapida(this, true);
        frm.setVisible(true);

        Emprestimo emprestimo = frm.getEmprestimo();

        if (emprestimo != null) {

            // Verifica se a pessoa tem email cadastrado
            if (emprestimo.getFuncionario().getEmail() == null || emprestimo.getFuncionario().getEmail().equalsIgnoreCase("")) {
                JOptionPane.showMessageDialog(this, "Funcionário NÃO tem EMAIL cadastrado no sistema.", null, JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Verifica se tem protocolo cadastrado na listagem
            if (cobrancaoDao.verificaJaCadastradoPorProtocoloPendentes(emprestimo.getProtocolo())) {
                JOptionPane.showMessageDialog(this, emprestimo.getProtocolo() + " - Protocolo já consta na listagem.", null, JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Verifica se tem protocolo cadastrado
            String protocoloSemPonto = emprestimo.getProtocolo().replace(".", "").replace("-", "");

            if (protocoloSemPonto.equalsIgnoreCase("")) {
                JOptionPane.showMessageDialog(this, protocoloSemPonto + " - Não consta PROTOCOLO no cadastro.", null, JOptionPane.ERROR_MESSAGE);
                return;
            }

            int resposta = JOptionPane.showConfirmDialog(this, "Deseja cadastrar o protocolo: " + emprestimo.getProtocolo() + "?", null, JOptionPane.YES_NO_OPTION);

            if (resposta == JOptionPane.YES_OPTION) {

                cobranca = new Cobranca();

                // Cobranca(int idCobranca, String data, Funcionario funcionario, String protocolo, String motivo, Emprestimo emprestimo, String status, String dataEnvio, Usuario usuario, int quantidade) 
                this.cobranca.setData(hoje());
                this.cobranca.setFuncionario(emprestimo.getFuncionario());
                this.cobranca.setProtocolo(emprestimo.getProtocolo());
                this.cobranca.setMotivo(emprestimo.getCelular().getMarca().getMarca() + ", IMEI: " + emprestimo.getCelular().getImei1());

                this.cobranca.setStatus("PENDENTE");
                this.cobranca.setEmprestimo(emprestimo);
                this.cobranca.setUsuario(usuarioLogado); // Pega o usuário da sessão  

                this.cobranca.setQuantidade(0);

                cobrancaoDao.insert(cobranca);

                carregaGrelha();
                JOptionPane.showMessageDialog(this, "Cadastrado com Sucesso.", null, JOptionPane.INFORMATION_MESSAGE);

            } else if (resposta == JOptionPane.NO_OPTION) {
                JOptionPane.showMessageDialog(this, "Operação Cancelada.", null, JOptionPane.INFORMATION_MESSAGE);
            }

        }


    }//GEN-LAST:event_btnPesquisaRapidaActionPerformed

