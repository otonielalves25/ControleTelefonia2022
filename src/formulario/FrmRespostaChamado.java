    private void gerarResposta() {

        int id = Integer.parseInt(txtCodigo.getText());
        String empretimoChipOuCelular = "";
        String aparelhoChip = "";
        String forma = "";
        String protocoloChamado = "";

        Emprestimo emprestimo = new EmprestimoDao().retornaPorID(id);

        String nome = emprestimo.getFuncionario().getNome().trim();
        String chamado = emprestimo.getChamado();
        String protocoloTeste = emprestimo.getProtocolo().replace(".", "").replace("-", "").trim();
        String protocolo = emprestimo.getProtocolo();
        String data = emprestimo.getDataEmprestimo();
        String localidade = emprestimo.getFuncionario().getLocalidade().getNomeLocalidade();

        String imei = (emprestimo.getCelular().getImei1() != null) ? emprestimo.getCelular().getImei1() : "";
        String chip = (emprestimo.getChip().getCodigoChip() != null) ? emprestimo.getChip().getCodigoChip() : "";
        String numero = (emprestimo.getChip().getNumeroLinha() != null) ? emprestimo.getChip().getNumeroLinha() : "";
        String operadora = (emprestimo.getChip().getEmpresa().getNomeEmpresa() != null) ? emprestimo.getChip().getEmpresa().getNomeEmpresa() : "";
        String tipo = (emprestimo.getCelular().getMarca().getCategoria().getCategoria() != null) ? emprestimo.getCelular().getMarca().getCategoria().getCategoria() : "";
        String marcaModelo = (emprestimo.getCelular().getMarca().getMarca() != null) ? emprestimo.getCelular().getMarca().getMarca() : "";
        String responsavel = emprestimo.getUsuario().getNome();
        String ramal = emprestimo.getUsuario().getRamal();
        // VERIFICAR A FORMA DE ENVIO

        if (radMalote.isSelected()) {
            forma = "via MALOTE";
        } else if (radMaos.isSelected()) {
            forma = "EM MÃOS";
        } else if (radSedex.isSelected()) {
            forma = "via SEDEX";
        }

        // EMPRESTIMO DE CELULAR OU CHIPO
        if (!imei.equalsIgnoreCase("") && !chip.equalsIgnoreCase("")) { //EMPRESTIMO CELULAR E CHIP
            empretimoChipOuCelular = " Aparelho: " + tipo + " - " + marcaModelo + " - Nº do IMEI: " + imei + ", Chip: " + chip + " - nº linha: " + numero + " - Operadora: " + operadora + ".";
            aparelhoChip = "aparelho";
        } else if (!imei.equalsIgnoreCase("") && chip.equalsIgnoreCase("")) {//EMPRESTIMO SOMENTE CELULAR
            empretimoChipOuCelular = " Aparelho: " + tipo + " - " + marcaModelo + " - Nº do IMEI: " + imei + ".";
            aparelhoChip = "aparelho";
        } else if (imei.equalsIgnoreCase("") && !chip.equalsIgnoreCase("")) {//EMPRESTIMO SOMENTE CHIP
            empretimoChipOuCelular = "Chip: " + chip + " -  nº linha: " + numero + " - Operadora: " + operadora + ".";
            aparelhoChip = "chip";
        }

        // VERIFICA SE É CHAMADO OU PROTOCOLO
        if (!protocoloTeste.equalsIgnoreCase("")) {
            protocoloChamado = "seu protocolo: " + protocolo;
        } else if (!chamado.equalsIgnoreCase("")) {
            protocoloChamado = "seu chamado: " + chamado;
        } else {
            protocoloChamado = "sua solicitação";
        }

        // MONTAGEM DO TEXTO PARA TELA
        String texto = "Sr(a), " + nome + ", " + protocoloChamado + " foi atendido.\n\n"
                + "Enviamos para " + localidade + " o " + aparelhoChip + ", " + forma + ", dia: " + data + ". \n\n"
                + "1 - " + empretimoChipOuCelular + " \n\n"
                + "Qualquer dúvida, é só ligar no 767.\n\n"
                + "Att. " + responsavel + " - Ramal: " + ramal + " - DOT/COOGI/DETRAN";

        txtTexto.setText(texto);

    }

